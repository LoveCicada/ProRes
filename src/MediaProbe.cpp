        return QString::fromUtf8("\xE8\xAF\xB7\xE5\x85\x88\xE6\x89\x93\xE5\xBC\x80\xE4\xB8\x80\xE4\xB8\xAA\xE5\xAD\x98\xE5\x9C\xA8\xE7\x9A\x84\xE6\x96\x87\xE4\xBB\xB6\xE3\x80\x82");

    MediaInfoDLL::MediaInfo mi;
