        return QString::fromUtf8("\xE6\x97\xA0\xE6\xB3\x95\xE5\x8A\xA0\xE8\xBD\xBD\x20\x4D\x65\x64\x69\x61\x49\x6E\x66\x6F\x2E\x64\x6C\x6C\xE3\x80\x82\xE8\xAF\xB7\xE6\x8A\x8A\xE5\xAE\x83\xE6\x94\xBE\xE5\x9C\xA8\xE7\xA8\x8B\xE5\xBA\x8F\xE6\x97\x81\xE8\xBE\xB9\xE3\x80\x82");

    mi.Option(__T("Language"), __T("zh-CN"));
    mi.Option(__T("Complete"), __T("0"));
    if (!mi.Open(path.toStdWString()))
        return QString::fromUtf8("\x4D\x65\x64\x69\x61\x49\x6E\x66\x6F\x20\xE6\x97\xA0\xE6\xB3\x95\xE6\x89\x93\xE5\xBC\x80\xE8\xAF\xA5\xE6\x96\x87\xE4\xBB\xB6\xE3\x80\x82");

    const MediaInfoDLL::String text = mi.Inform();
    mi.Close();
