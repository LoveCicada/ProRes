        return QString::fromUtf8("\x4D\x65\x64\x69\x61\x49\x6E\x66\x6F\x20\xE6\xB2\xA1\xE6\x9C\x89\xE8\xBF\x94\xE5\x9B\x9E\xE5\x86\x85\xE5\xAE\xB9\xE3\x80\x82");
